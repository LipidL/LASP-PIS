"""Generate frozen physics fixtures with the independent simple-dftd3 1.2.1 package.

Run: python d3/tools/generate_reference.py > d3/tests/reference.inc
Requires numpy and dftd3==1.2.1. Test execution itself has no Python dependency.
"""
import dftd3
import numpy as np
from dftd3.interface import DispersionModel, RationalDampingParam

assert dftd3.__version__ == "1.2.1"
bohr, hartree = 0.52917726, 27.21138505

# Coordinates and cutoffs are rounded to the same float32 inputs as the CUDA API.
cases = [
    ("water_dimer", [8, 1, 1, 8, 1, 1],
     [[2, 2, 2], [2.95, 2, 2], [1.8, 2.9, 2], [4.7, 2.4, 2.2],
      [5.6, 2.5, 2.2], [4.5, 3.3, 2.1]], np.eye(3) * 30, 3.2, 7.1),
    ("periodic_mixed", [6, 8, 1, 7, 14, 17],
     [[.3, .4, .5], [1.6, .5, .7], [.1, 1.4, .6], [2.2, 2.1, 1.2],
      [4.4, 3.2, 2.8], [3.3, 4.6, 4.1]],
     [[6.7, 0, 0], [1.2, 6.4, 0], [-.8, .7, 6.9]], 3.4, 8.1),
    ("self_images", [6], [[.2, .3, .4]],
     [[2.4, 0, 0], [.3, 2.6, 0], [.1, -.2, 2.8]], 3.1, 6.3),
    ("cn_larger_than_dispersion", [6, 8, 1, 7, 14, 17],
     [[.3, .4, .5], [1.6, .5, .7], [.1, 1.4, .6], [2.2, 2.1, 1.2],
      [4.4, 3.2, 2.8], [3.3, 4.6, 4.1]], np.eye(3) * 12, 5.3, 2.8),
    ("heavy_elements", [18, 29, 40, 79, 94],
     [[1, 1, 1], [3.1, 1.3, 1.2], [1.2, 4.1, 1.5], [3.3, 3.2, 2.1],
      [5.2, 4.1, 3.2]], np.eye(3) * 20, 5.1, 8.2),
]

def array(a):
    return "{" + ", ".join(format(float(v), ".16g") for v in np.asarray(a).flat) + "}"

print("// Generated by tools/generate_reference.py with simple-dftd3 1.2.1, ATM disabled.")
print("static const std::vector<Fixture> fixtures = {")
for name, z, xyz, cell, cn, disp in cases:
    xyz, cell = np.asarray(xyz, dtype=np.float32), np.asarray(cell, dtype=np.float32)
    cn, disp = float(np.float32(cn)), float(np.float32(disp))
    model = DispersionModel(np.array(z), xyz.astype(float) / bohr,
                            lattice=cell.astype(float) / bohr, periodic=np.ones(3, dtype=bool))
    model.set_realspace_cutoff(disp / bohr, disp / bohr, cn / bohr)
    result = model.get_dispersion(RationalDampingParam(s6=1., s8=.7875, a1=.4289,
                                                       a2=4.4407, s9=0.), grad=True)
    print(f'    {{"{name}", {array(z)}, {array(xyz)}, {array(cell)},')
    print(f'     {{{cn:.16g}, {disp:.16g}}}, {float(result["energy"]) * hartree:.16g},')
    print(f'     {array(-result["gradient"] * hartree / bohr)},')
    print(f'     {array(-result["virial"] * hartree)}}},')
print("};")
