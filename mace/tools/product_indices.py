#!/usr/bin/env python3
"""Emit canonical MH1 product connectivity from a processed PWMH1001 archive.

Only indices are emitted; trained coefficients always remain runtime data.
"""

import argparse
from pathlib import Path
import struct


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    records = {}
    with args.archive.open("rb") as stream:
        if stream.read(8) != b"PWMH1001":
            parser.error("expected a processed PWMH1001 archive")
        for _ in range(struct.unpack("<I", stream.read(4))[0]):
            length, size = struct.unpack("<IQ", stream.read(12))
            name = stream.read(length).decode()
            records[name] = stream.read(size)
    terms = [list(struct.iter_unpack("<5i", records[f"layer{k}.product.terms"]))
             for k in range(2)]
    if terms[1] != terms[0][:len(terms[1])]:
        parser.error("expected layer 1 to share the scalar terms of layer 0")
    lines = ["#pragma once", "// Generated by mace/tools/product_indices.py; indices only.",
             "namespace mace {", "struct PolyTerm {", "    int output, degree, a, b, c;", "};",
             "template<int LayerIndex>", "struct FixedProduct;", "template<>",
             "struct FixedProduct<0> {", f"    static constexpr int count = {len(terms[0])};",
             "    inline static constexpr PolyTerm terms[] = {"]
    lines += ["        {" + ", ".join(map(str, term)) + "}," for term in terms[0]]
    lines += ["    };", "};", "template<>", "struct FixedProduct<1> {",
              f"    static constexpr int count = {len(terms[1])};",
              "    inline static constexpr const PolyTerm* terms = FixedProduct<0>::terms;",
              "};", "} // namespace mace", ""]
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
