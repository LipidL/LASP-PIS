#!/usr/bin/env python3
"""Regenerate mathematical (not trained) e3nn 0.4.4 coupling constants.

Development only. The MH1 exporter uses the default float32 wigner_3j table.
Only angular degrees used by the supported MH1 tensor products are emitted.
"""
from pathlib import Path
import torch
torch.serialization.add_safe_globals([slice])
from e3nn import o3

rows = []
for l1 in (0, 1):
    for l2 in range(4):
        for lo in range(abs(l1-l2), min(3, l1+l2)+1):
            cg = o3.wigner_3j(l1, l2, lo, dtype=torch.float32)
            for a, b, c in (cg.abs() > 1e-14).nonzero().tolist():
                rows.append(f"  {{{l1},{l2},{lo},{a},{b},{c},{float(cg[a,b,c]):.17g}}},")
Path(__file__).resolve().parents[1].joinpath("src/cg.inc").write_text(
    "// Generated by tools/generate_cg.py; e3nn 0.4.4 real-basis Wigner 3j.\n"
    "// Mathematical constants only; no checkpoint weights.\n" + "\n".join(rows) + "\n")
